  const isPdf = operation.startsWith("pdf.");
  fileInput.accept = isPdf ? ".pdf,application/pdf" : ".jpg,.jpeg,.png,.gif,.webp,.bmp,.tif,.tiff,image/jpeg,image/png,image/gif,image/webp,image/bmp,image/tiff";
